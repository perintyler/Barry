/**
 * @barry/ui — Icon Button template
 *
 * A compact button containing only an icon (SVG).
 * Used for toolbar actions, sidebar toggles, close buttons, etc.
 *
 * @typedef {Object} IconButtonOptions
 * @property {string} icon - SVG string
 * @property {string} [label] - Accessible label (aria-label)
 * @property {string} [title] - Tooltip text
 * @property {'ghost'|'subtle'|'danger'} [variant='ghost']
 * @property {'sm'|'md'} [size='md']
 * @property {string} [id]
 * @property {boolean} [disabled=false]
 * @property {string} [className]
 */

function esc(s) {
  if (typeof s !== 'string') return '';
  return s.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/"/g, '&quot;');
}

/**
 * @param {IconButtonOptions} opts
 * @returns {string} HTML string
 */
export function iconButton(opts) {
  const {
    icon,
    label = '',
    title = '',
    variant = 'ghost',
    size = 'md',
    id = '',
    disabled = false,
    className = '',
  } = opts;

  const classes = [
    'icon-btn',
    `icon-btn-${variant}`,
    size === 'sm' ? 'icon-btn-sm' : '',
    className,
  ].filter(Boolean).join(' ');

  const idAttr = id ? ` id="${esc(id)}"` : '';
  const ariaLabel = label ? ` aria-label="${esc(label)}"` : '';
  const titleAttr = title ? ` title="${esc(title)}"` : '';
  const disabledAttr = disabled ? ' disabled' : '';

  return `<button type="button"${idAttr} class="${classes}"${ariaLabel}${titleAttr}${disabledAttr}>${icon}</button>`;
}

