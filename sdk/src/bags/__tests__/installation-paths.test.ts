import { mkdirSync, mkdtempSync, readlinkSync, realpathSync, rmSync, symlinkSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { afterEach, expect, it, vi } from "vitest";
import { barryCurrentDir, barryAppSupportDir } from "../../services/home.mjs";
import { builtinBagsDir, discoverBuiltinBags } from "../builtin.js";
import { linkExternals } from "../build.js";
let scratch: string;
afterEach(() => { vi.unstubAllEnvs(); if (scratch) rmSync(scratch, { recursive: true, force: true }); });
it("keeps builtin discovery and external links through current", () => {
  scratch = mkdtempSync(join(tmpdir(), "barry-bag-installation-"));
  vi.stubEnv("BARRY_HOME", scratch);
  vi.stubEnv("BARRY_BUILTIN_DIR", undefined);
  vi.stubEnv("BARRY_BAGS_BUILD_DIR", join(scratch, "build"));
  const target = join(scratch, "release");
  mkdirSync(join(target, "bags/fixture"), { recursive: true });
  writeFileSync(join(target, "identity.yaml"), "name: Barry\nbags: [fixture]\n");
  writeFileSync(join(target, "bags/fixture/bag.yaml"), "name: fixture\ndescription: fixture\n");
  mkdirSync(join(target, "node_modules/better-sqlite3"), { recursive: true });
  writeFileSync(join(target, "node_modules/better-sqlite3/package.json"), '{"name":"better-sqlite3","main":"index.js"}');
  writeFileSync(join(target, "node_modules/better-sqlite3/index.js"), "");
  mkdirSync(barryAppSupportDir(), { recursive: true });
  symlinkSync(realpathSync(target), barryCurrentDir());
  expect(builtinBagsDir()).toBe(join(barryCurrentDir(), "bags"));
  expect(discoverBuiltinBags().local).toEqual({ fixture: "fixture" });
  linkExternals(barryCurrentDir());
  expect(readlinkSync(join(scratch, "build/node_modules/better-sqlite3"))).toBe(join(barryCurrentDir(), "node_modules/better-sqlite3"));
  vi.stubEnv("BARRY_BUILTIN_DIR", join(target, "bags"));
  expect(builtinBagsDir()).toBe(join(target, "bags"));
});
